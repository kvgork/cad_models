#!/usr/bin/env python3
"""Write the print list (how many of each STL to print) and the fastener BOM into each
product README.

    python3 tools/printlist.py                      # every folder with cad/ + exports/
    python3 tools/printlist.py strandbeest_gripper/v4_thumb-wheel
    python3 tools/printlist.py --check              # exit 1 if a README list is missing or stale

Quantities:
- Folder with an assembly script (cad/<PROJ>-9NNN_*.json with component.create):
  count the components per part number, skipping bom_type "purchased" (lib/ parts).
- Folder without one (single parts): 1 of each exported STL.
Every exported STL must be in the count and every counted part must have an STL,
otherwise the script fails.

The list goes between <!-- printlist:start --> and <!-- printlist:end -->. When the
markers are missing, a "## Print list" section is inserted before the first
Print / Hardware / Files heading, or appended at the end.

Fastener BOM: from <folder>/fasteners.json (hand-maintained, the source of truth):
    {"note": "...", "lines": [{"qty": 2, "where": "J2", "items": ["M3x22 ...", "M3 nyloc ..."],
                               "approx": false}]}
Each item string may start with "<n>× " for n per position. Written between
<!-- fasteners:start --> and <!-- fasteners:end -->, right after the print list:
a shopping list (totals per item) and a per-position table. A folder without
fasteners.json fails --check; use {"note": "No fasteners.", "lines": []}.
"""
import glob
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import parts  # noqa: E402

ROOT = parts.ROOT
START, END = '<!-- printlist:start -->', '<!-- printlist:end -->'
FSTART, FEND = '<!-- fasteners:start -->', '<!-- fasteners:end -->'
PER_RE = re.compile(r'^(\d+)× (.+)$')
STL_RE = re.compile(r'^([A-Z0-9]+-\d{4})_[a-z0-9-]+_([A-Z0-9]+)\.stl$')
ASSY_RE = re.compile(r'^[A-Z0-9]+-9\d{3}_[a-z0-9-]+\.json$')
BEFORE = ('## Print', '## Hardware', '## Files')


def assembly_counts(cad):
    """Printed components per PN from the assembly script, or None if there is none."""
    for path in sorted(glob.glob(os.path.join(cad, '*.json'))):
        if not ASSY_RE.match(os.path.basename(path)):
            continue
        cmds = json.load(open(path, encoding='utf-8'))
        meta = {c['params']['component']: c['params'] for c in cmds
                if c.get('command') == 'component.metadata.set'}
        comps = [c['params']['name'] for c in cmds if c.get('command') == 'component.create']
        if not comps:
            continue
        n = Counter()
        for comp in comps:
            m = meta.get(comp)
            if m is None:
                raise SystemExit(f'{path}: component {comp} has no component.metadata.set')
            if m.get('bom_type') != 'purchased':
                n[m['part_number']] += 1
        return os.path.basename(path), n
    return None


def build_list(folder):
    stls = {}
    for path in sorted(glob.glob(os.path.join(ROOT, folder, 'exports', '*.stl'))):
        m = STL_RE.match(os.path.basename(path))
        if not m:
            raise SystemExit(f'{path}: not named <PN>_<name>_<REV>.stl')
        stls[m.group(1)] = os.path.basename(path)
    if not stls:
        return None
    assy = assembly_counts(os.path.join(ROOT, folder, 'cad'))
    if assy:
        src, n = assy
        missing = sorted(set(n) - set(stls))
        extra = sorted(set(stls) - set(n))
        if missing or extra:
            raise SystemExit(f'{folder}: assembly {src} vs exports/ mismatch: '
                             f'no STL for {missing}, STL not in assembly {extra}')
        note = f'Quantities counted from the assembly `cad/{src}` (purchased parts left out).'
    else:
        n = Counter({pn: 1 for pn in stls})
        note = 'Single parts: print one of each.'
    reg = parts.register()
    rows = ['| Qty | File (`exports/`) | Part | Material |', '|---|---|---|---|']
    for pn in sorted(stls):
        r = reg.get(pn, {})
        desc = re.sub(r'\s*\([^)]*\bqty\b[^)]*\)', '', r.get('Description', '?'))  # PARTS.md qty notes
        rows.append(f"| {n[pn]} | `{stls[pn]}` | {desc} | "
                    f"{r.get('Material / process', '?')} |")
    total = sum(n.values())
    return '\n'.join([
        START,
        '<!-- generated by tools/printlist.py; do not edit by hand -->',
        f'**{total} prints from {len(stls)} STL files.** {note} '
        'The `.3mf` and `.step` of each part are next to the STL.',
        '',
        *rows,
        END,
    ])


def place(text, block):
    if START in text and END in text:
        a, b = text.index(START), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    section = '## Print list\n\n' + block + '\n\n'
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.startswith(BEFORE) and not line.startswith('## Print list'):
            return ''.join(lines[:i]) + section + ''.join(lines[i:])
    return text.rstrip('\n') + '\n\n' + section.rstrip('\n') + '\n'


def natural(name):
    return [int(t) if t.isdigit() else t for t in re.split(r'(\d+)', name)]


def build_fasteners(folder):
    path = os.path.join(ROOT, folder, 'fasteners.json')
    if not os.path.exists(path):
        return None
    data = json.load(open(path, encoding='utf-8'))
    total, approx, order = Counter(), set(), []
    rows = ['| Qty | Fasteners (each) | Where |', '|---|---|---|']
    for ln in data['lines']:
        q, tilde = ln['qty'], '~' if ln.get('approx') else ''
        shown = []
        for it in ln['items']:
            m = PER_RE.match(it)
            per, name = (int(m.group(1)), m.group(2)) if m else (1, it)
            if name not in total:
                order.append(name)
            total[name] += q * per
            if ln.get('approx'):
                approx.add(name)
            shown.append(it)
        rows.append(f"| {tilde}{q} | {' + '.join(shown)} | {ln['where']} |")
    out = [FSTART, '<!-- generated by tools/printlist.py from fasteners.json; edit that file -->']
    if data.get('note'):
        out += [data['note'], '']
    if total:
        out += ['**Shopping list**', '', '| Qty | Item |', '|---|---|']
        out += [f"| {'~' if n in approx else ''}{total[n]} | {n} |" for n in sorted(order, key=natural)]
        out += ['', '**Where they go**', '', *rows]
    out.append(FEND)
    return '\n'.join(out)


def place_fasteners(text, block):
    if FSTART in text and FEND in text:
        a, b = text.index(FSTART), text.index(FEND) + len(FEND)
        return text[:a] + block + text[b:]
    section = '## Fastener BOM\n\n' + block + '\n'
    e = text.index(END) + len(END)
    nl = text.find('\n', e)
    nl = len(text) if nl < 0 else nl + 1
    return text[:nl] + '\n' + section + text[nl:]


def folders():
    out = set()
    for path in glob.glob(os.path.join(ROOT, '**', 'exports'), recursive=True):
        d = os.path.dirname(path)
        if os.path.isdir(os.path.join(d, 'cad')) and '/lib/' not in d + '/':
            out.add(os.path.relpath(d, ROOT))
    return sorted(out)


def main(argv):
    check = '--check' in argv
    targets = [a.rstrip('/') for a in argv if a != '--check'] or folders()
    bad = 0
    for folder in targets:
        block = build_list(folder)
        if block is None:
            continue
        readme = os.path.join(ROOT, folder, 'README.md')
        text = open(readme, encoding='utf-8').read() if os.path.exists(readme) else ''
        new = place(text, block)
        fb = build_fasteners(folder)
        if fb is None:
            print(f'MISSING {folder}/fasteners.json')
            bad = 1
        else:
            new = place_fasteners(new, fb)
        if new == text:
            print(f'ok      {folder}')
        elif check:
            print(f'STALE   {folder}/README.md')
            bad = 1
        else:
            open(readme, 'w', encoding='utf-8').write(new)
            print(f'updated {folder}/README.md')
    return bad


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
